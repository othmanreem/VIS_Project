import assert from 'node:assert/strict';
import { classifyAreaGroups,profileAreaGroups } from '../src/areaGroups.js';
const years=[2020,2025];
const bins=[{id:'a',members:[0,1,2],counts:[1,2]},{id:'b',members:[3,4,5],counts:[2,1]},{id:'c',members:[6,7],counts:[1,1]},{id:'empty',members:[],counts:[0,0]}];
const records=Array.from({length:8},(_,i)=>({i,yr:[2020,2025,2025,2020,2020,2025,2020,2025][i],sev:i===2?2:3,casualties:[],feature:{properties:{light_conditions:1,road_surface_conditions:1,junction_detail:0,speed_limit:30}}}));
const classification=classifyAreaGroups(bins,years,2020,2025);
assert.deepEqual(classification.groups.map(g=>g.bins.map(b=>b.id)),[['a'],['b'],['c']]);
const all=profileAreaGroups(classification,records,2025);
assert.deepEqual(all.map(g=>g.n),[2,1,1]);assert.equal(all[0].share,50);
const filtered=profileAreaGroups(classification,records,2025,r=>r.sev===2);
assert.deepEqual(filtered.map(g=>g.n),[1,0,0]);assert.equal(filtered[1].share,null);
assert.deepEqual(filtered.map(g=>g.bins.map(b=>b.id)),[['a'],['b'],['c']]);
assert.equal(filtered[0].share,100);assert.equal(filtered[0].conditions.find(c=>c.label==='30 mph roads').count,1);
const earlier=profileAreaGroups(classification,records,2020);
assert.deepEqual(earlier.map(g=>g.n),[1,2,1]);
const reverse=classifyAreaGroups(bins,years,2025,2020);
assert.deepEqual(reverse.groups.map(g=>g.bins.map(b=>b.id)),[['b'],['a'],['c']]);
const same=classifyAreaGroups(bins,years,2020,2020);
assert.equal(same.groups[0].bins.length,0);assert.equal(same.groups[1].bins.length,0);
console.log('Area groups: fixed membership, refinement filters, empty samples, profile year and reversed comparisons passed');
